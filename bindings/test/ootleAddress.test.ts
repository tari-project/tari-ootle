import { describe, expect, it } from "vitest";
import { DecodedOotleAddress, decodeOotleAddress, encodeOotleAddress, validateOotleAddress } from "../src";

describe("OotleAddress de/encoding", () => {
  function makeDecodedAddress() {
    return {
      network: "igor",
      accountPublicKey: "a1b2c3d4e5f60718293a4b5c6d7e8f90123456789abcdef0123456789abcdef0",
      viewOnlyKey: "0fedcba9876543210fedcba9876543210fedcba9876543210fedcba98765432a",
    } as DecodedOotleAddress;
  }

  it("encodes and decodes a valid address", () => {
    const sample = makeDecodedAddress();

    const address = encodeOotleAddress(sample);

    let parsed: DecodedOotleAddress;
    expect(() => {
      parsed = decodeOotleAddress(address);
    }).not.toThrow();

    expect(parsed.network).toEqual(sample.network);
    expect(parsed.viewOnlyKey).toEqual(sample.viewOnlyKey);
    expect(parsed.accountPublicKey).toEqual(sample.accountPublicKey);
  });

  it("encodes and decodes address with destinationTag", () => {
    const sample = makeDecodedAddress();
    const destinationTagString = "Invoice #12345";
    const check = encodeOotleAddress(sample);
    sample.destinationTag = destinationTagString;

    const address = encodeOotleAddress(sample);

    expect(address).not.toEqual(check);

    let parsed: DecodedOotleAddress;
    expect(() => {
      parsed = decodeOotleAddress(address);
    }).not.toThrow();

    expect(parsed.network).toEqual(sample.network);
    expect(parsed.viewOnlyKey).toEqual(sample.viewOnlyKey);
    expect(parsed.accountPublicKey).toEqual(sample.accountPublicKey);
    expect(parsed.destinationTag).toEqual(destinationTagString);
  });

  it("encodes and decodes a 64-byte destinationTag on the longest prefix", () => {
    const sample = makeDecodedAddress();
    sample.network = "esmeralda";
    sample.destinationTag = "x".repeat(64);

    const address = encodeOotleAddress(sample);
    const parsed = decodeOotleAddress(address);

    expect(address.startsWith("otl_esm_")).toBe(true);
    expect(parsed.destinationTag).toEqual(sample.destinationTag);
    expect(validateOotleAddress(address)).toBe(true);
  });

  it("decodes a destinationTag that is not UTF-8 as bytes", () => {
    const sample = makeDecodedAddress();
    const destinationTag = new Uint8Array([0xff, 0xfe, 0x00, 0x80]);
    sample.destinationTag = destinationTag;

    const parsed = decodeOotleAddress(encodeOotleAddress(sample));

    expect(parsed.destinationTag).toEqual(destinationTag);
  });

  it("throws on invalid address", () => {
    expect(() => decodeOotleAddress("invalidAddress")).toThrow();
  });

  it("throws on invalid public key hex length", () => {
    let sample1 = makeDecodedAddress();
    sample1.accountPublicKey += "deadbeaf";
    expect(() => encodeOotleAddress(sample1)).toThrow();

    let sample2 = makeDecodedAddress();
    sample2.accountPublicKey = sample2.accountPublicKey.slice(1);
    expect(() => encodeOotleAddress(sample2)).toThrow();
  });

  it("throws if address is tampered", () => {
    const sample = makeDecodedAddress();
    const address = encodeOotleAddress(sample);
    // Tamper with the address by changing a character
    const tamperedAddress = address.slice(0, -1) + (address.slice(-1) === "a" ? "b" : "a");
    expect(() => decodeOotleAddress(tamperedAddress)).toThrow();
  });

  it("decodes a known address correctly", () => {
    // This address was generated by the rust version of OotleAddress
    let s =
      "otl_loc_1nsy5c5mfn7jgmg5nm3s3m4vr829tgpeehmymkme6k5wszde6wc7zcfwtyyxwn62tqefqyfyjangalt4zrygzwyf8c6c2jtfqyd8dk0gtwcv5x";
    let r = decodeOotleAddress(s);
    expect(r.network).toEqual("localnet");
    expect(r.accountPublicKey).toEqual("9c094c53699fa48da293dc611dd5833a8ab40739bec9bb6f3ab51d01373a763c");
    expect(r.viewOnlyKey).toEqual("2c25cb210ce9e94b0652022492ecd1dfaea21910271127c6b0a92d20234edb3d");
  });

  it("throws on unsupported network prefix", () => {
    const sample = makeDecodedAddress();
    // Temporarily change network to an unsupported one
    (sample as any).network = "unsupportednet";
    expect(() => encodeOotleAddress(sample)).toThrow();
  });
});
